using System.Text;

namespace InceptionTools;

/// <summary>
/// Typed interoperability metadata for the weapon table at 3EDB:2ED8.
/// The repository intentionally does not contain the executable's verbatim table bytes.
/// </summary>
public sealed record WeaponReferenceDefinition(
    string Name,
    byte Damage,
    byte Selector,
    byte HeatAndEffect,
    byte PackedRanges,
    byte MaximumRange,
    byte Skill)
{
    public byte[] EncodeRecord()
    {
        byte[] record = new byte[0x11];
        byte[] name = Encoding.ASCII.GetBytes(Name);
        if (name.Length > 11)
            throw new InvalidOperationException("Weapon names cannot exceed eleven ASCII bytes.");

        name.CopyTo(record, 0);
        record[0x0B] = Damage;
        record[0x0C] = Selector;
        record[0x0D] = HeatAndEffect;
        record[0x0E] = PackedRanges;
        record[0x0F] = MaximumRange;
        record[0x10] = Skill;
        return record;
    }
}

