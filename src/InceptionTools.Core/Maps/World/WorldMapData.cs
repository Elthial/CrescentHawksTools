    public static byte[] CreateSeedTable() => CreateSeedTable(OriginalRandomSeed);

    /// <summary>
    /// Expands a 24-bit RNG state into the exact table consumed by the original map
    /// subdivision code. The seed is written as 0xHHMMLL, matching the three bytes at
    /// 3EDB:4FC2, 4FC1 and 4FC0.
    /// </summary>
    public static byte[] CreateSeedTable(uint randomSeed)
    {
        if (randomSeed > 0xFFFFFF)
            throw new ArgumentOutOfRangeException(nameof(randomSeed),
                "The original RNG state contains exactly three bytes.");
        byte low = (byte)randomSeed;
        byte middle = (byte)(randomSeed >> 8);
        byte high = (byte)(randomSeed >> 16);
        var table = new byte[SeedTableLength];
        for (int index = 0; index < table.Length; index++)
        {
            byte carryFromLow = (byte)((low >> 1) & 1);
            byte carryFromHigh = (byte)(high >> 7);
            byte carryFromMiddle = (byte)(middle >> 7);
            byte newHigh = (byte)((high << 1) | carryFromLow);
            byte newMiddle = (byte)((middle << 1) | carryFromHigh);
            byte subtraction = (byte)((low >> 2) - low - (1 - carryFromMiddle));
            byte newLow = (byte)((low >> 1) | ((subtraction & 1) << 7));
            low = newLow;
            middle = newMiddle;
            high = newHigh;
            table[index] = (byte)(newLow ^ newMiddle);
        }
        return table;
    }
